/**
 * Сценарий Приветственного тура (релиз 1.2) — единый источник массива шагов.
 *
 * Тур переработан из «обзора меню» (релиз 0.6, 6 шагов) в сквозной сценарий из
 * 15 шагов, где шаг завершается одним из четырёх событий (поле `await`):
 *
 *   - `'nav'`    — клик по пункту верхнего уровня NAV с атрибутом
 *                  `data-tour-target="<key>"` (существующая механика 0.6);
 *   - `'click'`  — клик по произвольному элементу страницы, адресуемому через
 *                  `data-tour-action="<action>"` (кнопки «Создать проект»,
 *                  «Создать Дело», свободный слот сетки и т.п.);
 *   - `'event'`  — успешное сохранение сущности: экран после `res.ok` диспатчит
 *                  на `document` кастомное событие (`wolf:project-saved` и др.),
 *                  движок двигает шаг только по факту события. Это единственный
 *                  честный способ отличить «нажал Сохранить» от «сохранилось» —
 *                  при ошибке валидации тур не уезжает вперёд;
 *   - `'finish'` — завершающий шаг: двигается кнопкой «Завершить тур» в самой
 *                  подсказке (клика по интерфейсу не требуется).
 *
 * 🐺 и счётчик «шаг N из 15» вводятся под ADR-0008 (точечное исключение из
 * тихого контракта 0.3, только внутри узлов оверлея тура). Сквозная нумерация
 * шагов 1..15: в исходной заявке пропущен номер 13, поэтому заявочные 14/15/16
 * становятся сквозными 13/14/15.
 *
 * Соответствие тикет → сквозные шаги:
 *   02 → 1–2   03 → 3–4   04 → 5–6   05 → 7–9
 *   06 → 10–12   08 → 13–14   09 → 15
 *
 * Счётчик `n` — это сквозной номер шага для строки «шаг N из 15», а НЕ индекс в
 * массиве. Сквозной номер 2 закреплён за экраном выбора стартового профиля
 * (`/onboarding/profile`, «шаг 1 заявки») — это отдельный маршрут ДО запуска
 * движка, поэтому в массиве `STEPS` его нет: приветственное окно несёт `n: 1`,
 * следующий шаг — сразу `n: 3`. Каждый шаг объявляет свой `n` явно; движок
 * показывает `step.n`, а не позицию в массиве.
 *
 * Форма элемента шага:
 *
 *   {
 *     n: 1,                              // номер для счётчика (1..15)
 *     title: '…',                        // заголовок подсказки (🐺-префикс — в тексте)
 *     text: '…',                         // тело подсказки
 *     await: 'nav' | 'click' | 'event' | 'finish',
 *     key: 'morning',                    // для await:'nav' — значение data-tour-target
 *     target: '[data-tour-action="…"]',  // для await:'click' — CSS-селектор цели
 *     event: 'wolf:project-saved',       // для await:'event' — имя document-события
 *     hole: 'morning' | '[data-tour-action="…"]' | null,
 *                                        // что подсвечивать вырезом; null — без выреза
 *     placement: 'anchored' | 'center',  // 'center' — модальное окно по центру
 *   }
 *
 * Тексты приведены к глоссарию `CONTEXT.md` и к фактическому поведению кода
 * решениями владельца из `grill.md` (реш. B/C/D/E/G). Правки текста и
 * расстановка `data-tour-action` по экранам — тикеты 02–09.
 */

